async def _diagnose_case(case: EvalCase, embedder: KoSimCSEEmbedder) -> None:
    """실패 케이스의 raw distance rank → boost → final rank 흐름 출력."""
    query_text = build_query_text(case.request)
    vec: list[float] = embedder.embed([query_text])[0]

    collection = await get_collection(WELFARE_COLLECTION)

    def _query() -> Any:
        return collection.query(
            query_embeddings=[vec],  # type: ignore[arg-type]
            n_results=min(case.request.top_k * 5, 100),
        )

    raw: Any = await asyncio.to_thread(_query)
    distances: list[float] = raw["distances"][0]
    metadatas: list[dict[str, str]] = raw["metadatas"][0]

    # raw 순위별 (serv_id당 최고 섹션 청크) 집계
    raw_best: dict[str, tuple[int, dict[str, str], float, float, float]] = {}
    for raw_rank, (meta, dist) in enumerate(zip(metadatas, distances), start=1):
        serv_id = meta["serv_id"]
        boost = _profile_boost(case.request, meta)
        score = _rank_score(case.request, meta, dist)
        current = raw_best.get(serv_id)
        if current is None or score > current[4]:
            raw_best[serv_id] = (raw_rank, meta, dist, boost, score)

    ranked = sorted(raw_best.values(), key=lambda x: x[4], reverse=True)
    expected = set(case.expected_ids)

    print(f"\nDIAGNOSE {case.name}  query={query_text}")
    print(
        f"  {'#':>3}  {'raw':>4}  {'dist':>6}  {'boost':>6}  {'score':>6}  serv_id          serv_nm"
    )
    for final_rank, (raw_rank, meta, dist, boost, score) in enumerate(ranked[:15], start=1):
        marker = "* " if meta["serv_id"] in expected else "  "
        print(
            f"  {marker}{final_rank:>2}.  raw={raw_rank:>3}  "
            f"dist={dist:.3f}  boost={boost:+.3f}  score={score:.3f}  "
            f"{meta['serv_id']}  {meta['serv_nm'][:28]}"
        )


def _rank_of(result_ids: list[str], expected_ids: tuple[str, ...]) -> int | None:
    expected = set(expected_ids)
    for idx, serv_id in enumerate(result_ids, start=1):
        if serv_id in expected:
            return idx
    return None


async def _index_snapshot() -> tuple[int, int, set[str]]:
    collection = await get_collection(WELFARE_COLLECTION)

    def _get() -> Any:
        return collection.get(include=["metadatas"])

    raw: Any = await asyncio.to_thread(_get)
    service_ids = {
        meta["serv_id"]
        for meta in raw["metadatas"]
        if meta is not None and isinstance(meta.get("serv_id"), str)
    }
    return len(raw["ids"]), len(service_ids), service_ids


def _validation_error(case_name: str, field: str, serv_id: str, detail: str) -> str:
    return (
        "EVAL_CASE_VALIDATION_ERROR "
        f"case={case_name!r} field={field!r} id={serv_id!r} detail={detail}"
    )


def _validate_eval_cases(indexed_service_ids: set[str]) -> list[str]:
    errors: list[str] = []

    if len(EVAL_CASES) != EXPECTED_EVAL_CASE_COUNT:
        errors.append(
            _validation_error(
                "EVAL_CASES",
                "length",
                "-",
                f"expected {EXPECTED_EVAL_CASE_COUNT}, got {len(EVAL_CASES)}",
            )
        )

    names = [case.name for case in EVAL_CASES]
    for name, count in Counter(names).items():
        if count > 1:
            errors.append(
                _validation_error(name, "name", name, f"duplicate name appears {count} times")
            )

    for case in EVAL_CASES:
        case_name = case.name or "<empty>"
        if not case.name.strip():
            errors.append(_validation_error(case_name, "name", "-", "name must not be empty"))
        if not case.expected_ids:
            errors.append(
                _validation_error(case_name, "expected_ids", "-", "expected_ids must not be empty")
            )
        if not case.notes.strip():
            errors.append(_validation_error(case_name, "notes", "-", "notes must not be empty"))
        if case.request.top_k != 10:
            errors.append(
                _validation_error(
                    case_name,
                    "request.top_k",
                    str(case.request.top_k),
                    "top_k must be exactly 10",
                )
            )

        for field_name, service_ids in (
            ("expected_ids", case.expected_ids),
            ("excluded_ids", case.excluded_ids),
        ):
            for serv_id in service_ids:
                if serv_id not in indexed_service_ids:
                    errors.append(
                        _validation_error(
                            case_name,
                            field_name,
                            serv_id,
                            "serv_id is not present in the current Chroma index",
                        )
                    )

    return errors


async def evaluate(verbose: bool, diagnose: bool = False) -> int:
    chunk_count, service_count, indexed_service_ids = await _index_snapshot()
    validation_errors = _validate_eval_cases(indexed_service_ids)
    if validation_errors:
        for error in validation_errors:
            print(error, file=sys.stderr)
        return 2

    embedder = KoSimCSEEmbedder()

    ranks: list[int | None] = []
    rows: list[tuple[EvalCase, int | None, list[tuple[str, str, float]], list[str]]] = []
    latencies_ms: list[float] = []
    eligibility_status_counts: Counter[str] = Counter()

    for case in EVAL_CASES:
        started_at = time.perf_counter()
        response = await search_welfare(case.request, embedder)
        latencies_ms.append((time.perf_counter() - started_at) * 1000)
        eligibility_status_counts.update(result.eligibility_status for result in response.results)
        results = [(r.serv_id, r.serv_nm, r.score) for r in response.results]
        result_ids = [serv_id for serv_id, _, _ in results]
        rank = _rank_of(result_ids, case.expected_ids)
        excluded_hits = [serv_id for serv_id in result_ids if serv_id in case.excluded_ids]
        ranks.append(rank)
        rows.append((case, rank, results, excluded_hits))

    total = len(ranks)

    def recall_at(k: int) -> float:
        return sum(rank is not None and rank <= k for rank in ranks) / total

    mrr = sum(0.0 if rank is None else 1.0 / rank for rank in ranks) / total
    cases_with_excluded_hits = sum(1 for _, _, _, excluded_hits in rows if excluded_hits)
    exclusion_pass_rate = (total - cases_with_excluded_hits) / total
    avg_latency_ms = sum(latencies_ms) / len(latencies_ms)
    p95_index = min(len(latencies_ms) - 1, math.ceil(len(latencies_ms) * 0.95) - 1)
    p95_latency_ms = sorted(latencies_ms)[p95_index]
    returned_result_count = sum(eligibility_status_counts.values())

    print("Search Quality Evaluation")
    print(f"index: {chunk_count} chunks / {service_count} services")
    print(f"cases: {total}")
    print(f"recall@1: {recall_at(1):.3f}")
    print(f"recall@3: {recall_at(3):.3f}")
    print(f"recall@5: {recall_at(5):.3f}")
    print(f"recall@10: {recall_at(10):.3f}")
    print(f"mrr: {mrr:.3f}")
    print(f"exclusion_pass_rate: {exclusion_pass_rate:.3f}")
    print(f"avg_latency_ms: {avg_latency_ms:.1f}")
    print(f"p95_latency_ms: {p95_latency_ms:.1f}")
    print("eligibility_status_distribution:")
    for status in ("likely", "needs_more_info", "unlikely"):
        count = eligibility_status_counts[status]
        ratio = 0.0 if returned_result_count == 0 else count / returned_result_count
        print(f"  {status}: {count} ({ratio:.3f})")
    print()

    for case, rank, results, excluded_hits in rows:
        expected_passed = rank is not None and rank <= 5
        status = "PASS" if expected_passed and not excluded_hits else "FAIL"
        rank_text = "-" if rank is None else str(rank)
        print(f"{status} {case.name}: rank={rank_text} expected={','.join(case.expected_ids)}")
        if case.excluded_ids:
            excluded_text = ",".join(case.excluded_ids)
            hit_text = "-" if not excluded_hits else ",".join(excluded_hits)
            print(f"  excluded: {excluded_text}")
            print(f"  excluded_hits: {hit_text}")
        if verbose or status == "FAIL":
            print(f"  query: {build_query_text(case.request)}")
            print(f"  notes: {case.notes}")
            for pos, (serv_id, serv_nm, score) in enumerate(results[:10], start=1):
                marker = "*" if serv_id in case.expected_ids else " "
                print(f"  {marker}{pos:>2}. {serv_id} {serv_nm} score={score:.3f}")
        if diagnose and status == "FAIL":
            await _diagnose_case(case, embedder)
    return 0 if recall_at(5) >= 0.8 and cases_with_excluded_hits == 0 else 1


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--verbose", action="store_true", help="Print top results for every case")
    parser.add_argument(
        "--diagnose",
        action="store_true",
        help="For FAIL cases: show raw distance rank, boost, and final rank side-by-side",
    )
    args = parser.parse_args()
    raise SystemExit(asyncio.run(evaluate(verbose=args.verbose, diagnose=args.diagnose)))


if __name__ == "__main__":
    main()
